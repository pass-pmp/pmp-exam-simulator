// FORMAT EXPANSION STORAGE (new in this pack):
// The bank's BankQuestion type expresses single answer items only, so
// this pack defines three additional item shapes below and uses them
// only inside this file:
//   Pack9MultipleResponseQuestion  kind "multiple-response": the full
//     option list (five options) plus correctSet, the indexes of every
//     correct option, and chooseCount, how many the candidate must
//     select. Scoring in version 2 is all or nothing, as the exam
//     scores these items.
//   Pack9MatchingQuestion  kind "matching": leftItems (five prompts),
//     rightOptions (six choices, exactly one is a distractor), and
//     correctMap, where correctMap[i] is the rightOptions index that
//     matches leftItems[i].
//   Pack9ChartInterpretationQuestion  kind "chart-interpretation": a
//     single answer item (four options, correct index) plus chart, the
//     structured chart data the version 2 renderer draws from. The
//     scenario text narrates every chart value in words, so the item
//     and its audio recording are complete without the visual.
// Every new format item carries the same fields as a standard item
// (domain, format, topic, processGroup, scenario, stem, explanation,
// trap) plus difficulty. The 70 standard items below use the S
// constructor exactly like Packs 1 to 8; their difficulty values are
// recorded in the pack production record, as in those packs, and the
// pack as a whole is exactly 25 foundational, 50 standard, 25 advanced.
